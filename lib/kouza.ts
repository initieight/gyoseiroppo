/**
 * アガルートの提携条件で必須の計測パラメータ。
 * 既に ? を含むURLには & で連結する。
 */
const AGAROOT_UTM = 'utm_source=afb&utm_medium=aff&utm_campaign=afb-txt';

export function appendUtm(url: string, providerId: ProviderId): string {
  if (providerId !== 'agaroot') return url;
  if (url === '#' || url === '') return url;
  return url + (url.includes('?') ? '&' : '?') + AGAROOT_UTM;
}

/** 提携承認済みかどうか（'#' はまだ未承認） */
export function isLinkReady(providerId: ProviderId): boolean {
  return AFFILIATE_LINKS[providerId].url !== '#';
}

export function ctaHref(providerId: ProviderId): string {
  const { url } = AFFILIATE_LINKS[providerId];
  return appendUtm(url, providerId);
}

